// Token Radar's model: the peer-multiple model.
//
// A pre-token protocol's implied value is what its token would be worth if the market priced it
// the way it prices the listed protocols in its own category. The snapshot carries everything the
// model needs and nothing it does not: TVL, seven-day growth, the day tracking began, the chains,
// and, for the protocols whose token already trades, the market cap.
//
//   peer multiple  = median(mcap_usd / tvl_usd) over the listed protocols in the same category
//                    (at least 3 peers; otherwise the median over every listed protocol),
//                    winsorised to [multiple_floor, multiple_cap]
//   growth         = clamp(change_7d, growth_floor, growth_cap) per cent
//   growthMult     = 1 + (growth / 100) x growth_weight
//   maturity       = maturity_floor + min(age_days, maturity_days) / maturity_days x maturity_range
//                    (age_days unknown: unknown_age_days)
//   chainMult      = 1 + chain_step x min(chains - 1, chain_max_extra)
//   implied        = max(1, round(tvl_usd x peer multiple x growthMult x maturity x chainMult))
//
// No protocol name is ever special-cased: the same function scores every row, and the peer
// multiple is recomputed from the snapshot on every run, never a hardcoded list of names. A
// protocol "records no token" when DefiLlama's record carries none; the model never claims a
// protocol has no token, and never predicts whether or when one launches.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

